#!/usr/bin/env python3
# linux's vga font -> the C array the console draws with.
#
#   usage: font2c.py font_8x16.c > drivers/font.c
#
# the input is lib/fonts/font_8x16.c from linux, the 8x16 font its vga
# console starts with: 256 glyphs of sixteen rows, one hex byte a row,
# in code page 437, the order the vga's own rom keeps them in. it is
# GPL-2.0, which is what this kernel is, so it is a file of the kernel
# like any other rather than a thing with a license of its own beside
# LICENSE. the notice at the top of it is carried across whole.
#
# the parse is strict on purpose: exactly 4096 bytes, and the glyph
# comments counting 0 to 255 in order, so a file that is not that font
# stops here rather than turning into a console of wrong letters.

import re
import sys

HEADER = """\
// SPDX-License-Identifier: GPL-2.0-only
/*
 * drivers/font.c
 * Jose A. Perez de Azpillaga <azpijr@gmail.com>, 2026
 * the console font: the vga 8x16, from linux.
 */

/*
 * the glyphs are linux's, from lib/fonts/font_8x16.c, in code page 437,
 * the vga's own order. that file's notice, in full:
 *
%s
 *
 * this file is GENERATED by tools/font2c.py, dont edit it by hand
 */
"""


def notice(text):
    """the comment above the first #include, without its box. the box is
    made of comment markers, which cannot sit inside a comment of this
    file's, so what is kept is every line of words in it."""
    out = []
    for line in text[:text.index("#include")].splitlines():
        line = line.strip()
        if re.fullmatch(r"[/*\-\s]*", line):
            continue
        out.append(" *     " + re.sub(r"^(//|/\*+)\s*|\s*\*+/$", "", line))
    if not out:
        sys.exit("font2c: no notice at the top of the input")
    return "\n".join(out)


def glyphs(text):
    rows = [int(b, 16) for b in re.findall(r"^\s*0x([0-9a-fA-F]{2}),", text, re.M)]
    if len(rows) != 256 * 16:
        sys.exit("font2c: %d bytes of glyph, expected 4096" % len(rows))
    seen = [int(n) for n in re.findall(r"/\* (\d+) 0x[0-9a-fA-F]+ ", text)]
    if seen != list(range(256)):
        sys.exit("font2c: the glyphs are not 0 to 255 in order")
    return [rows[i * 16:(i + 1) * 16] for i in range(256)]


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: font2c.py font_8x16.c")

    text = open(sys.argv[1], encoding="utf-8").read()
    print(HEADER % notice(text))
    print('#include "font.h"')
    print()
    print("const uint8_t console_font[256][16] = {")
    for cp, rows in enumerate(glyphs(text)):
        name = chr(cp) if 32 <= cp < 127 else "."
        print("    /* 0x%02x '%s' */" % (cp, name))
        print("    { %s," % ", ".join("0x%02x" % b for b in rows[:8]))
        print("      %s }," % ", ".join("0x%02x" % b for b in rows[8:]))
    print("};")


if __name__ == "__main__":
    main()
